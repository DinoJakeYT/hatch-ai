const { contextBridge, ipcRenderer } = require('electron');

const invoke = (ch, ...args) => ipcRenderer.invoke(ch, ...args);
const on = ch => cb => ipcRenderer.on(ch, (_e, payload) => cb(payload));

contextBridge.exposeInMainWorld('hatch', {
  listChats: () => invoke('chats:list'),
  getChat: id => invoke('chat:get', id),
  send: args => invoke('chat:send', args),
  stop: id => invoke('chat:stop', id),
  setChat: (id, patch) => invoke('chat:set', id, patch),
  deleteChat: (id, opts) => invoke('chat:delete', id, opts),
  setGroups: groups => invoke('groups:set', groups),
  respondPermission: (reqId, decision) => invoke('perm:respond', reqId, decision),
  undo: (id, index) => invoke('chat:undo', id, index),
  redo: (id, index) => invoke('chat:redo', id, index),
  runnables: id => invoke('project:runnables', id),
  play: (id, name) => invoke('project:play', id, name),
  pickFolder: () => invoke('folder:pick'),
  openPath: p => invoke('shell:open', p),

  connections: opts => invoke('connections:get', opts),
  signIn: provider => invoke('auth:signin', provider),
  signInWithBrowser: () => invoke('auth:browser'),
  cancelSignIn: () => invoke('auth:cancel'),
  signOut: provider => invoke('auth:signout', provider),
  setKey: (name, value) => invoke('keys:set', name, value),
  openRouterModels: () => invoke('openrouter:models'),

  getSettings: () => invoke('settings:get'),
  setSettings: patch => invoke('settings:set', patch),
  usage: opts => invoke('usage:get', opts),
  getMemory: () => invoke('memory:get'),
  setMemory: (kind, text) => invoke('memory:set', kind, text),
  compressMemory: (kind, model) => invoke('memory:compress', kind, model),
  saveCompressed: (kind, text) => invoke('memory:saveCompressed', kind, text),
  openMemory: kind => invoke('memory:open', kind),
  listGuides: () => invoke('guides:list'),
  getGuide: name => invoke('guides:get', name),
  setGuide: (name, text) => invoke('guides:set', name, text),
  openGuides: () => invoke('guides:open'),
  toolchain: opts => invoke('toolchain:get', opts),
  listSkills: () => invoke('skills:list'),
  findSkills: url => invoke('skills:find', url),
  installSkills: (repo, picks) => invoke('skills:install', repo, picks),
  importSkillFolder: () => invoke('skills:importFolder'),
  setSkillEnabled: (name, on) => invoke('skills:setEnabled', name, on),
  removeSkill: name => invoke('skills:remove', name),
  getSkill: name => invoke('skills:get', name),
  saveSkill: data => invoke('skills:save', data),
  decideSkill: (chatId, index, decision, edited) => invoke('skills:decide', chatId, index, decision, edited),
  openSkills: () => invoke('skills:open'),
  libsStatus: () => invoke('libs:status'),
  installRaylib: () => invoke('libs:installRaylib'),
  onLibsProgress: on('libs:progress'),
  localModels: () => invoke('models:list'),
  pullModel: name => invoke('models:pull', name),
  cancelPull: name => invoke('models:cancelPull', name),
  deleteModel: name => invoke('models:delete', name),
  onPullProgress: on('models:progress'),

  appInfo: () => invoke('app:info'),
  updateStatus: () => invoke('update:get'),
  checkForUpdate: () => invoke('update:check'),
  installUpdate: () => invoke('update:install'),
  onUpdateStatus: on('update:status'),

  startOvernight: args => invoke('overnight:start', args),
  stopOvernight: id => invoke('overnight:stop', id),
  onOpenChat: on('open-chat'),
  onChatEvent: on('chat:event'),
  onAuthEvent: on('auth:event'),
  onUsageChanged: on('usage:changed'),
  onMemoryChanged: on('memory:changed'),
});
